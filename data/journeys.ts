/**
 * Journey map — the places HTH drives to from Ho Chi Minh City.
 *
 * Coordinates are WGS84 [longitude, latitude]. Most are the same points the
 * quote engine uses (`lib/quote.ts → places`), so the map, the estimator and
 * the booking form always agree. Where a place is visited for one specific
 * site (Củ Chi tunnels, Núi Bà Đen, Mũi Né dunes) the point sits on that site.
 *
 * Highlights were checked against public sources in November 2026
 * (VnExpress travel guides, Vietnam Airlines destination guides, Wikipedia,
 * provincial tourism pages). Keep each one specific: a place, a thing to do,
 * a fact a traveller can use. No adjectives doing the work.
 */

export type JourneyRegion = 'coast' | 'highlands' | 'mekong' | 'nearby' | 'business';
export type TripLength = 'transfer' | 'half' | 'day' | 'overnight' | 'multi';

type Text = { vi: string; en: string };

export interface Highlight {
  title: Text;
  body: Text;
}

export interface Journey {
  id: string;
  /** Matching id in lib/quote.ts places, used for distance, time and fare. */
  placeId: string;
  name: Text;
  /** Province or area shown under the name. */
  area: Text;
  coordinates: [number, number];
  region: JourneyRegion;
  trip: TripLength;
  tagline: Text;
  highlights: [Highlight, Highlight, Highlight];
  /** Best season, or a practical timing tip. */
  when?: Text;
  /** Slug of an existing route guide. */
  routeSlug?: { vi: string; en: string };
  /** Label priority on the overview: 1 always shown, 2 from 1.7× zoom, 3 from 3×. */
  tier: 1 | 2 | 3;
  /** Which side of the marker the name sits on. */
  anchor: 'n' | 's' | 'e' | 'w' | 'ne' | 'nw' | 'se' | 'sw';
}

